// Generate the paste-ready Worker using only Node.js built-ins.
import {mkdirSync, readFileSync, writeFileSync} from "node:fs";

const read = path => readFileSync(new URL(path, import.meta.url), "utf8").replace(/\r\n/g, "\n");
const core = read("src/core.mjs").replace(/^export /gm, "");
const nativeImport = 'import {connect} from "cloudflare:sockets";';
const entry = read("src/worker.mjs")
  .replace(nativeImport, "")
  .replace(/^import \{scheduled, serve\} from "\.\/core\.mjs";\n/m, "");
if (/^import /m.test(core + entry)) throw new Error("Unbundled import in dashboard source");
const output = [
  "// Generated by node workers/build-dashboard.mjs; edit workers/src instead.",
  "// Paste this whole file into BOTH probe Workers; configure each WORKER_ID and RESULTS binding.",
  nativeImport, "", core.trim(), "", entry.trim(), ""
].join("\n");
const target = new URL("worker-dashboard.js", import.meta.url);
if (process.argv.slice(2).length && process.argv[2] !== "--check") throw new Error("Only --check is supported");
if (process.argv[2] === "--check") {
  if (read("worker-dashboard.js") !== output) throw new Error("Dashboard JS is stale; run node workers/build-dashboard.mjs");
} else {
  writeFileSync(target, output);
  // Preserve the local download path previously given to the maintainer.
  mkdirSync(new URL("../build/", import.meta.url), {recursive: true});
  writeFileSync(new URL("../build/worker-dashboard.js", import.meta.url), output);
  console.log("Generated workers/worker-dashboard.js and build/worker-dashboard.js");
}
